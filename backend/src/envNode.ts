import type { Env } from './env';

/** Builds the Worker-style Env from process.env (local server, CLI jobs). Shared so jobs and the server read the same variables. */
export function nodeEnv(): Env {
  try { process.loadEnvFile(new URL('../.env', import.meta.url)); } catch { /* optional */ }
  const e = process.env;
  return {
    ENVIRONMENT: (e.ENVIRONMENT as Env['ENVIRONMENT']) ?? 'development',
    SQLITE_PATH: e.SQLITE_PATH,
    APP_SECRET: e.APP_SECRET, RESEND_API_KEY: e.RESEND_API_KEY, MAIL_FROM: e.MAIL_FROM,
    MAILPIT_URL: e.MAILPIT_URL ?? (e.ENVIRONMENT === 'test' ? undefined : 'http://127.0.0.1:8025'),
    SKIP_MX: e.SKIP_MX, TRUST_PROXY_HEADERS: e.TRUST_PROXY_HEADERS ?? '1', ALLOWED_ORIGINS: e.ALLOWED_ORIGINS,
    RATE_LIMIT_MULTIPLIER: e.RATE_LIMIT_MULTIPLIER,
    AI_API_KEY: e.AI_API_KEY, DEEPSEEK_API_KEY: e.DEEPSEEK_API_KEY, AI_BASE_URL: e.AI_BASE_URL, AI_MODEL: e.AI_MODEL, AI_DAILY_BUDGET: e.AI_DAILY_BUDGET, AI_USER_DAILY: e.AI_USER_DAILY, AI_TIMEOUT_MS: e.AI_TIMEOUT_MS, APP_URL: e.APP_URL,
    TELEGRAM_BOT_TOKEN: e.TELEGRAM_BOT_TOKEN, TELEGRAM_WEBHOOK_SECRET: e.TELEGRAM_WEBHOOK_SECRET, TELEGRAM_BOT_USERNAME: e.TELEGRAM_BOT_USERNAME, TELEGRAM_API_BASE: e.TELEGRAM_API_BASE,
    SENTRY_DSN: e.SENTRY_DSN, RELEASE: e.RELEASE, TURNSTILE_SECRET: e.TURNSTILE_SECRET, TURNSTILE_SITEKEY: e.TURNSTILE_SITEKEY,
    EMBED_API_KEY: e.EMBED_API_KEY, EMBED_BASE_URL: e.EMBED_BASE_URL, EMBED_MODEL: e.EMBED_MODEL,
  };
}
