-- Issue 6: skills suggested in the vacancy form for the selected industry.
-- The suggestions reference the SAME `skills` vocabulary as student profiles and vacancy requirements, so a suggested name is spelled exactly
-- like the student's skill and matching compares like with like. An admin can change the list later with plain SQL (no deploy):
--   INSERT INTO industry_skills (industry_key, skill_id, sort_order) SELECT 'retail', id, 11 FROM skills WHERE name_key = 'python';
-- 'general' is the fallback set for the "Other" industry and for a form where no industry is chosen yet.
CREATE TABLE industry_skills (
  industry_key TEXT    NOT NULL,
  skill_id     INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
  sort_order   INTEGER NOT NULL DEFAULT 100,
  PRIMARY KEY (industry_key, skill_id),
  CONSTRAINT industry_skills_key_chk CHECK (industry_key IN ('it_software', 'finance_banking', 'telecom', 'education', 'healthcare', 'retail', 'manufacturing', 'energy_oil_gas', 'logistics_transport', 'construction', 'media_marketing', 'government', 'consulting', 'tourism_hospitality', 'agriculture', 'other', 'general'))
);
CREATE INDEX industry_skills_order_idx ON industry_skills (industry_key, sort_order);

